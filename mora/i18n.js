const sourceText = new WeakMap();
const sourceAttributes = new WeakMap();

function readSavedLocale() {
  try {
    const saved = globalThis.localStorage?.getItem(STORAGE_KEY);
    return SUPPORTED_LOCALES.has(saved) ? saved : "ru";
  } catch {
    return "ru";
  }
}

let activeLocale = readSavedLocale();

function localizedValue(source, locale) {
  if (locale !== "uk") return source;
  if (UKRAINIAN[source]) return UKRAINIAN[source];

  const intentSummary = source.match(/^План содержит (\d+) действие\(й\)\. Ничего не изменится до вашего подтверждения\.$/);
  if (intentSummary) {
    return "План містить " + intentSummary[1] + " дію(ї). Нічого не зміниться без вашого підтвердження.";
  }

  const branch = source.match(/^Создана ветка (.+) · ревизия (\d+)(?: · родитель (.+)| · корневая ветка)$/);
  if (branch) {
    return "Створено гілку " + branch[1] + " · ревізія " + branch[2] +
      (branch[3] ? " · батьківська " + branch[3] : " · коренева гілка");
  }

  const deepTime = source.match(/^(.+) лет · отдельная BigInt-шкала, не системные часы$/);
  if (deepTime) return deepTime[1] + " років · окрема шкала BigInt, а не системний годинник";

  if (source.startsWith("A/B-план · текущий слот ")) {
    return source.split("\n").map((line) => {
      if (line.startsWith("A/B-план · текущий слот ")) {
        return line.replace("A/B-план · текущий слот ", "A/B-план · поточний слот ")
          .replace(" · целевой слот ", " · цільовий слот ");
      }
      return line
        .replace(/^Подпись пакета:/, "Підпис пакета:")
        .replace(/^Совместимость:/, "Сумісність:")
        .replace(/^Свободное место:/, "Вільне місце:")
        .replace(": не проверено", ": не перевірено")
        .replace(/^Этапы:/, "Етапи:")
        .replaceAll("verify-signed-metadata-and-payload", "перевірити підписані метадані та пакет")
        .replaceAll("verify-compatibility-and-capacity", "перевірити сумісність і місткість")
        .replaceAll("stage-inactive-slot", "підготувати неактивний слот")
        .replaceAll("run-health-checks", "виконати перевірки працездатності")
        .replaceAll("switch-boot-entry-atomically", "атомарно перемкнути запис завантаження")
        .replaceAll("retain-previous-slot-until-accepted-boot", "зберегти попередній слот до підтвердження запуску")
        .replace(/^Не переключайте записи загрузки, пока все условия не подтверждены\.$/,
          "Не перемикайте записи завантаження, доки всі умови не підтверджено.");
    }).join("\n");
  }

  return source;
}

function renderTextNode(node) {
  let state = sourceText.get(node);
  if (!state) {
    state = { source: node.nodeValue, rendered: node.nodeValue };
    sourceText.set(node, state);
  } else if (node.nodeValue !== state.rendered) {
    state.source = node.nodeValue;
    state.variants = null;
  }

  const original = state.source;
  const leadingLength = original.length - original.trimStart().length;
  const trailingStart = original.trimEnd().length;
  const leading = original.slice(0, leadingLength);
  const trailing = original.slice(trailingStart);
  const value = original.slice(leadingLength, trailingStart);
  const localized = state.variants && typeof state.variants[activeLocale] === "string"
    ? state.variants[activeLocale]
    : localizedValue(value, activeLocale);
  const next = leading + localized + trailing;
  state.rendered = next;
  if (node.nodeValue !== next) node.nodeValue = next;
}

function renderAttribute(element, name) {
  let values = sourceAttributes.get(element);
  if (!values) {
    values = new Map();
    sourceAttributes.set(element, values);
  }

  const current = element.getAttribute(name);
  let state = values.get(name);
  if (!state) {
    state = { source: current, rendered: current };
    values.set(name, state);
  } else if (current !== state.rendered) {
    state.source = current;
  }

  const next = localizedValue(state.source, activeLocale);
  state.rendered = next;
  if (current !== next) element.setAttribute(name, next);
}

export function getLocale() {
  return activeLocale;
}

export function setLocalizedText(element, source, variants = null) {
  if (!element) return;
  const original = String(source ?? "");
  element.textContent = original;
  const node = element.firstChild;
  if (node && node.nodeType === 3) {
    const localizedVariants = variants && typeof variants === "object"
      ? { ru: String(variants.ru ?? original), uk: String(variants.uk ?? original) }
      : null;
    sourceText.set(node, {
      source: original,
      rendered: original,
      variants: localizedVariants
    });
    renderTextNode(node);
  }
}

export function translate(source, locale = activeLocale) {
  return localizedValue(String(source ?? ""), locale);
}

export function applyLocale(root = globalThis.document) {
  if (!root || typeof root.querySelectorAll !== "function") return;
  const doc = root.ownerDocument || root;
  if (doc.documentElement) doc.documentElement.lang = activeLocale === "uk" ? "uk" : "ru";

  const walker = doc.createTreeWalker(root, 4);
  let node = walker.nextNode();
  while (node) {
    const parentName = node.parentElement?.tagName;
    if (parentName !== "SCRIPT" && parentName !== "STYLE" && parentName !== "TEXTAREA") {
      renderTextNode(node);
    }
    node = walker.nextNode();
  }

  for (const element of root.querySelectorAll("[placeholder], [aria-label], [title]")) {
    for (const name of ["placeholder", "aria-label", "title"]) {
      if (!element.hasAttribute(name)) continue;
      renderAttribute(element, name);
    }
  }
}

export function setLocale(locale) {
  if (!SUPPORTED_LOCALES.has(locale)) return activeLocale;
  activeLocale = locale;
  try {
    globalThis.localStorage?.setItem(STORAGE_KEY, locale);
  } catch {
    // The current session still changes language when storage is unavailable.
  }
  applyLocale();
  return activeLocale;
}

if (typeof document !== "undefined" && typeof MutationObserver !== "undefined" && document.documentElement) {
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      for (const added of record.addedNodes) {
        if (added.nodeType === 1) applyLocale(added);
        else if (added.nodeType === 3) renderTextNode(added);
      }
      if (record.type === "characterData" && record.target.nodeType === 3) {
        renderTextNode(record.target);
      }
    }
  });
  observer.observe(document.documentElement, { childList: true, subtree: true, characterData: true });
}
