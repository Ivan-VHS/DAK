"""Source package synthesis, integrity validation and local Jora catalog."""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import tempfile
from datetime import datetime, timezone
from pathlib import Path, PurePosixPath
from typing import Any

from .engine import analyze_formula, normalize_formula

PACKAGE_SCHEMA = "duckos.jora.app-package.v1"
CATALOG_SCHEMA = "duckos.jora.local-catalog.v1"
MAX_PACKAGE_FILES = 256
MAX_PACKAGE_BYTES = 128 * 1024 * 1024
MAX_GENERATED_TEXT = 4 * 1024 * 1024


class PackageError(ValueError):
    """Raised for invalid, unsafe or inconsistent Jora packages."""


def _json_bytes(value: Any) -> bytes:
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2, allow_nan=False) + "\n").encode("utf-8")


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _write_text(root: Path, relative: str, text: str) -> None:
    encoded = text.encode("utf-8")
    if len(encoded) > MAX_GENERATED_TEXT:
        raise PackageError(f"Generated source exceeds the {MAX_GENERATED_TEXT}-byte text limit: {relative}")
    target = root / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.is_symlink():
        raise PackageError(f"Refusing to write through a symbolic link: {relative}")
    target.write_bytes(encoded)


def _write_json(root: Path, relative: str, value: Any) -> None:
    target = root / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.is_symlink():
        raise PackageError(f"Refusing to write through a symbolic link: {relative}")
    target.write_bytes(_json_bytes(value))


def _file_inventory(root: Path) -> dict[str, dict[str, Any]]:
    rows: dict[str, dict[str, Any]] = {}
    total = 0
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise PackageError(f"Package must not contain symbolic links: {path.relative_to(root)}")
        if not path.is_file():
            continue
        relative = path.relative_to(root).as_posix()
        pure = PurePosixPath(relative)
        if pure.is_absolute() or any(part in {"", ".", ".."} for part in pure.parts):
            raise PackageError(f"Unsafe package path: {relative}")
        data = path.read_bytes()
        total += len(data)
        if total > MAX_PACKAGE_BYTES:
            raise PackageError(f"Package exceeds the {MAX_PACKAGE_BYTES}-byte limit")
        rows[relative] = {"size_bytes": len(data), "sha256": _sha256(data)}
        if len(rows) > MAX_PACKAGE_FILES:
            raise PackageError(f"Package exceeds the {MAX_PACKAGE_FILES}-file limit")
    return rows


def _reaper_source(analysis: dict[str, Any]) -> str:
    identity = analysis["identity"]
    ids = analysis["formula"]["component_ids"]
    component_line = " + ".join(ids)
    safe_name = json.dumps(identity["display_name"], ensure_ascii=False)
    safe_hash = json.dumps(analysis["formula"]["formula_hash"])
    safe_components = json.dumps(component_line, ensure_ascii=False)
    return (
        "# Generated by DuckOS Jora. Review this source before executing it.\n"
        "make app_name := " + safe_name + "\n"
        "make formula_hash := " + safe_hash + "\n"
        "make formula_components := " + safe_components + "\n"
        'emit "Jora application: " ++ app_name\n'
        'emit "Formula hash: " ++ formula_hash\n'
        'emit "Components: " ++ formula_components\n'
        "\n"
        "craft describe_component(component_id) {\n"
        "    yield component_id\n"
        "}\n"
        "\n"
        'emit "Source generated successfully."\n'
    )


def _python_helper() -> str:
    return '''"""Deterministic text/glossary helpers generated by Jora.

No translation provider is bundled or contacted by this module.
"""
from __future__ import annotations

from typing import Any


def validate_segment(segment: dict[str, Any]) -> dict[str, Any]:
    required = {"id", "source_text"}
    missing = sorted(required - set(segment))
    if missing:
        raise ValueError("missing segment fields: " + ", ".join(missing))
    if not isinstance(segment["id"], str) or not segment["id"]:
        raise ValueError("segment id must be non-empty text")
    if not isinstance(segment["source_text"], str):
        raise ValueError("source_text must be text")
    return dict(segment)


def apply_glossary(text: str, glossary: dict[str, str]) -> str:
    if not isinstance(text, str) or not isinstance(glossary, dict):
        raise TypeError("text and glossary have invalid types")
    result = text
    for source, target in sorted(glossary.items(), key=lambda pair: (-len(pair[0]), pair[0])):
        if not isinstance(source, str) or not isinstance(target, str):
            raise ValueError("glossary entries must map text to text")
        if source:
            result = result.replace(source, target)
    return result


def translation_request(segment: dict[str, Any], target_locale: str) -> dict[str, str]:
    item = validate_segment(segment)
    if not isinstance(target_locale, str) or not target_locale:
        raise ValueError("target_locale is required")
    return {
        "segment_id": item["id"],
        "source_text": item["source_text"],
        "target_locale": target_locale,
        "provider_state": "not_configured",
    }
'''


def _rust_helper() -> str:
    return '''//! Jora audio frame-boundary helper. This is not a real-time audio device driver.
pub fn validate_frame_window(total_frames: usize, start: usize, length: usize) -> Result<(), &'static str> {
    let end = start.checked_add(length).ok_or("frame window overflow")?;
    if length == 0 || end > total_frames {
        return Err("frame window is outside the source buffer");
    }
    Ok(())
}
'''


def _c_helper() -> str:
    return '''/* Jora audio frame-boundary helper. No device access or DSP callback. */
#include <stddef.h>

int jora_validate_frame_window(size_t total_frames, size_t start, size_t length) {
    if (length == 0 || start > total_frames || length > total_frames - start) {
        return 0;
    }
    return 1;
}
'''


def _typescript_helper() -> str:
    return '''export interface JoraAppIdentity {
  readonly appId: string;
  readonly displayName: string;
  readonly formulaHash: string;
}

export function describeJoraApp(identity: JoraAppIdentity): string {
  if (!identity.appId || !identity.displayName || !/^[0-9a-f]{64}$/.test(identity.formulaHash)) {
    throw new Error("Invalid Jora application identity");
  }
  return identity.displayName + " (" + identity.appId + ")";
}
'''


def _demo_audio_bytes() -> bytes:
    import io
    import wave

    buffer = io.BytesIO()
    with wave.open(buffer, "wb") as stream:
        stream.setnchannels(1)
        stream.setsampwidth(2)
        stream.setframerate(16000)
        stream.writeframes(b"\x00\x00" * 8000)
    return buffer.getvalue()


