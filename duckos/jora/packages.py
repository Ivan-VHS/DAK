def _build_files(stage: Path, analysis: dict[str, Any]) -> None:
    ids = set(analysis["formula"]["component_ids"])
    _write_text(stage, "source/main.rpr", _reaper_source(analysis))
    if "audio_editor" in ids or "speech_to_text" in ids or "text_to_speech" in ids:
        audio_path = stage / "content" / "audio" / "demo.wav"
        audio_path.parent.mkdir(parents=True, exist_ok=True)
        audio_path.write_bytes(_demo_audio_bytes())
    if "translator" in ids or "glossary" in ids or "subtitle_export" in ids:
        _write_text(stage, "helpers/translation_tools.py", _python_helper())
    language_names = {item["language"] for item in analysis["languages"]["languages"]}
    if "Rust" in language_names:
        _write_text(stage, "helpers/audio_frames.rs", _rust_helper())
    elif "C" in language_names:
        _write_text(stage, "helpers/audio_frames.c", _c_helper())
    if "TypeScript" in language_names:
        _write_text(stage, "web/jora_app.ts", _typescript_helper())
    _write_json(stage, "architecture/formula.json", analysis["formula"])
    _write_json(stage, "architecture/graph.json", analysis["graph"])
    _write_json(stage, "architecture/languages.json", analysis["languages"])
    _write_json(stage, "content/demo-project.json", _demo_content(analysis))
    _write_json(stage, "store/listing.json", {
        "schema": "duckos.jora.store-listing.v1",
        "app_id": analysis["identity"]["app_id"],
        "display_name": analysis["identity"]["display_name"],
        "slug": analysis["identity"]["slug"],
        "tagline": analysis["identity"]["tagline"],
        "description": analysis["identity"]["description"],
        "formula": analysis["formula"]["component_ids"],
        "languages": [item["language"] for item in analysis["languages"]["languages"]],
        "screenshots": [],
        "visual_status": "not_captured",
        "publication_status": "local_draft",
    })
    readme = (
        "# " + analysis["identity"]["display_name"] + "\n\n"
        + analysis["identity"]["tagline"] + ".\n\n"
        + "Formula: " + " + ".join(analysis["formula"]["component_ids"]) + "\n\n"
        + "## Generated project\n\n"
        + "- source/main.rpr — main Reaper source.\n"
        + "- architecture/ — canonical formula, bounded integration graph and language selection report.\n"
        + "- content/demo-project.json — coherent synthetic sample data.\n"
        + "- store/listing.json — store metadata draft.\n\n"
        + "## Runtime and trust boundary\n\n"
        + "This package contains generated source and metadata. The Reaper reference runtime must be used for an explicit static check. "
        + "No generated source is executed during package creation or verification. No OS installation, public-store publication, "
        + "microphone access, network request or device operation is performed by this package.\n"
    )
    _write_text(stage, "README.md", readme)


def _safe_target(path: str | Path) -> tuple[Path, Path]:
    target = Path(path).expanduser()
    if not target.is_absolute():
        target = Path.cwd() / target
    if target.name in {"", ".", ".."}:
        raise PackageError("Package output must name a new directory")
    if target.suffix != ".jora":
        raise PackageError("Package output directory must use the .jora suffix")
    if target.is_symlink():
        raise PackageError("Package output must not be a symbolic link")
    parent = target.parent
    parent.mkdir(parents=True, exist_ok=True)
    resolved_parent = parent.resolve(strict=True)
    if not resolved_parent.is_dir():
        raise PackageError("Package output parent is not a directory")
    resolved = resolved_parent / target.name
    if resolved.exists() or resolved.is_symlink():
        raise PackageError(f"Package output already exists: {resolved}")
    return resolved, resolved_parent


def _required_permissions(component_ids: set[str]) -> list[str]:
    permissions: set[str] = set()
    if "file_manager" in component_ids:
        permissions.add("filesystem.selected_paths")
    if component_ids & {"audio_editor", "video_editor", "text_to_speech"}:
        permissions.add("audio.output")
    if component_ids & {"speech_to_text"}:
        permissions.add("microphone.capture")
    if component_ids & {"cloud_sync", "cloud_streaming"}:
        permissions.add("network.outbound")
    return sorted(permissions)


def generate_package(formula: str, output: str | Path, *, profile: str = "desktop") -> dict[str, Any]:
    current_catalog = list_catalog()
    requested_formula = normalize_formula(formula)
    requested_hash = requested_formula["formula_hash"]
    existing_slugs = {
        item.get("slug") for item in current_catalog["applications"]
        if item.get("slug") and item.get("formula_hash") != requested_hash
    }
    analysis = analyze_formula(formula, profile=profile, existing_slugs=existing_slugs)
    target, parent = _safe_target(output)
    stage = Path(tempfile.mkdtemp(prefix=".jora-stage-", dir=parent))
    try:
        _build_files(stage, analysis)
        inventory = _file_inventory(stage)
        manifest = {
            "schema": PACKAGE_SCHEMA,
            "version": "1.0.0",
            "app": analysis["identity"],
            "formula": analysis["formula"],
            "formula_hash": analysis["formula"]["formula_hash"],
            "graph": {
                "schema": analysis["graph"]["schema"],
                "node_count": analysis["graph"]["node_count"],
                "edge_count": analysis["graph"]["edge_count"],
                "max_synergy_neighbors": analysis["graph"]["max_synergy_neighbors"],
                "topology": analysis["graph"]["topology"],
            },
            "languages": analysis["languages"],
            "generator": {"name": "DuckOS Jora", "version": "0.1.0"},
            "reaper": {"required": True, "compiler_assumption": "reference_runtime_static_check_only"},
            "permissions": _required_permissions(set(analysis["formula"]["component_ids"])),
            "dependencies": [],
            "files": inventory,
            "total_bytes": sum(item["size_bytes"] for item in inventory.values()),
            "verification": {"status": "not_checked", "source_check": "pending", "helper_checks": "pending"},
            "created_at": datetime.now(timezone.utc).isoformat(),
        }
        _write_json(stage, "jora.manifest.json", manifest)
        os.replace(stage, target)
    except Exception:
        shutil.rmtree(stage, ignore_errors=True)
        raise
    verification = verify_package(target)
    manifest_path = target / "jora.manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    manifest["verification"] = verification["verification"]
    _write_json(target, "jora.manifest.json", manifest)
    return {
        "schema": "duckos.jora.package-create.v1",
        "created": True,
        "package_path": str(target),
        "app": analysis["identity"],
        "formula_hash": analysis["formula"]["formula_hash"],
        "files": len(inventory),
        "total_bytes": manifest["total_bytes"],
        "verification": verification["verification"],
    }


def _load_manifest(package: Path) -> dict[str, Any]:
    if package.is_symlink() or not package.is_dir():
        raise PackageError("Package path must be a regular directory")
    manifest_path = package / "jora.manifest.json"
    if manifest_path.is_symlink() or not manifest_path.is_file():
        raise PackageError("jora.manifest.json is missing or is a symbolic link")
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise PackageError(f"Cannot read Jora manifest: {error}") from error
    if not isinstance(manifest, dict) or manifest.get("schema") != PACKAGE_SCHEMA:
        raise PackageError(f"Manifest schema must be {PACKAGE_SCHEMA}")
    return manifest


def _verify_helpers(package: Path, files: dict[str, Any]) -> dict[str, Any]:
    results: list[dict[str, Any]] = []
    for relative in sorted(files):
        path = package / relative
        if relative.endswith(".py"):
            try:
                compile(path.read_text(encoding="utf-8"), str(path), "exec")
                results.append({"file": relative, "status": "syntax_ok", "executed": False})
            except (OSError, SyntaxError, UnicodeError) as error:
                results.append({"file": relative, "status": "failed", "message": str(error), "executed": False})
        elif relative.endswith(".c"):
            compiler = shutil.which("cc") or shutil.which("gcc") or shutil.which("clang")
            if not compiler:
                results.append({"file": relative, "status": "toolchain_unavailable", "executed": False})
                continue
            try:
                with tempfile.TemporaryDirectory(prefix="jora-c-check-") as directory:
                    run = subprocess.run([compiler, "-std=c11", "-Wall", "-Wextra", "-Werror", "-fsyntax-only", str(path)],
                                         capture_output=True, text=True, encoding="utf-8", errors="replace",
                                         timeout=20, shell=False, cwd=directory)
                results.append({"file": relative, "status": "syntax_ok" if run.returncode == 0 else "failed",
                                "message": run.stderr[:4000], "executed": False})
            except (OSError, subprocess.TimeoutExpired) as error:
                results.append({"file": relative, "status": "failed", "message": str(error), "executed": False})
        elif relative.endswith(".ts"):
            compiler = shutil.which("tsc")
            if not compiler:
                results.append({"file": relative, "status": "toolchain_unavailable", "executed": False})
                continue
            try:
                with tempfile.TemporaryDirectory(prefix="jora-ts-check-") as directory:
                    run = subprocess.run([compiler, "--noEmit", "--target", "ES2022", "--strict", "--skipLibCheck", str(path)],
                                         capture_output=True, text=True, encoding="utf-8", errors="replace",
                                         timeout=30, shell=False, cwd=directory)
                results.append({"file": relative, "status": "syntax_ok" if run.returncode == 0 else "failed",
                                "message": run.stderr[:4000] or run.stdout[:4000], "executed": False})
            except (OSError, subprocess.TimeoutExpired) as error:
                results.append({"file": relative, "status": "failed", "message": str(error), "executed": False})
        elif relative.endswith(".rs"):
            compiler = shutil.which("rustc")
            if not compiler:
                results.append({"file": relative, "status": "toolchain_unavailable", "executed": False})
                continue
            try:
                with tempfile.TemporaryDirectory(prefix="jora-rust-check-") as directory:
                    output = str(Path(directory) / "jora_audio_frames.rmeta")
                    run = subprocess.run([compiler, "--crate-type", "lib", "--emit", "metadata", str(path), "-o", output],
                                         capture_output=True, text=True, encoding="utf-8", errors="replace",
                                         timeout=30, shell=False, cwd=directory)
                results.append({"file": relative, "status": "syntax_ok" if run.returncode == 0 else "failed",
                                "message": run.stderr[:4000], "executed": False})
            except (OSError, subprocess.TimeoutExpired) as error:
                results.append({"file": relative, "status": "failed", "message": str(error), "executed": False})
    failed = any(item["status"] == "failed" for item in results)
    unavailable = any(item["status"] == "toolchain_unavailable" for item in results)
    status = "failed" if failed else "incomplete" if unavailable else "checked"
    return {"status": status, "results": results, "generated_code_executed": False}


def verify_package(package_path: str | Path, *, reaper_workbench: Any = None) -> dict[str, Any]:
    raw_package = Path(package_path).expanduser()
    if raw_package.is_symlink():
        raise PackageError("Package directory must not be a symbolic link")
    package = raw_package.resolve(strict=True)
    manifest = _load_manifest(package)
    files = manifest.get("files")
    if not isinstance(files, dict) or not 1 <= len(files) <= MAX_PACKAGE_FILES:
        raise PackageError("Manifest files must be a bounded, non-empty object")
    total = 0
    for relative, metadata in files.items():
        if not isinstance(relative, str) or not isinstance(metadata, dict):
            raise PackageError("Invalid file inventory entry")
        pure = PurePosixPath(relative)
        if pure.is_absolute() or any(part in {"", ".", ".."} for part in pure.parts):
            raise PackageError(f"Unsafe file inventory path: {relative}")
        candidate = package.joinpath(*pure.parts)
        current = package
        for part in pure.parts:
            current = current / part
            if current.is_symlink():
                raise PackageError(f"Symbolic links are not allowed in a Jora package: {relative}")
        try:
            resolved = candidate.resolve(strict=True)
        except OSError as error:
            raise PackageError(f"Package file is missing: {relative}") from error
        if not resolved.is_relative_to(package) or not resolved.is_file():
            raise PackageError(f"Package path escapes the package root: {relative}")
        data = resolved.read_bytes()
        size = len(data)
        total += size
        if size != metadata.get("size_bytes") or _sha256(data) != metadata.get("sha256"):
            raise PackageError(f"Integrity check failed: {relative}")
        if total > MAX_PACKAGE_BYTES:
            raise PackageError(f"Package exceeds the {MAX_PACKAGE_BYTES}-byte limit")
    if total != manifest.get("total_bytes"):
        raise PackageError("Manifest total_bytes does not match file inventory")

    source = package / "source" / "main.rpr"
    if source.is_symlink() or not source.is_file():
        raise PackageError("source/main.rpr is missing")
    if reaper_workbench is None:
        from ..desktop.reaper import ReaperWorkbench
        reaper_workbench = ReaperWorkbench()
    if not reaper_workbench.available:
        source_check = {"available": False, "passed": False, "status": "reaper_not_found",
                        "message": "Initialize projects/reaper or configure DUCKOS_REAPER_ROOT.",
                        "source_executed": False}
    else:
        try:
            result = reaper_workbench.check(source)
            source_check = {
                "available": True, "passed": bool(result.get("ok")),
                "status": "passed" if result.get("ok") else "failed",
                "exit_code": result.get("exit_code"),
                "diagnostics": result.get("result") if result.get("result") is not None else result.get("stderr", "")[:4000],
                "source_executed": False,
            }
        except (OSError, ValueError, RuntimeError) as error:
            source_check = {"available": True, "passed": False, "status": "failed",
                            "message": str(error), "source_executed": False}
    helper_checks = _verify_helpers(package, files)
    passed = source_check["passed"] and helper_checks["status"] == "checked"
    verification_status = (
        "verified_preview" if passed else
        "verification_failed" if helper_checks["status"] == "failed" else
        "integrity_checked_source_unverified" if source_check["status"] == "reaper_not_found" else
        "verification_incomplete" if source_check["passed"] and helper_checks["status"] == "incomplete" else
        "verification_failed"
    )
    verification = {
        "status": verification_status,
        "integrity": "passed",
        "source_check": source_check,
        "helper_checks": helper_checks,
        "runtime_execution": "not_performed",
        "native_installation": "not_performed",
        "public_publication": "not_performed",
    }
    return {
        "schema": "duckos.jora.package-verify.v1",
        "ok": True,
        "package_path": str(package),
        "files_checked": len(files),
        "total_bytes_checked": total,
        "verification": verification,
    }


def _catalog_path(path: str | Path | None = None) -> Path:
    if path is not None:
        return Path(path).expanduser()
    return Path.home() / ".local" / "share" / "duckos" / "jora" / "catalog.v1.json"


def list_catalog(*, catalog_path: str | Path | None = None) -> dict[str, Any]:
    path = _catalog_path(catalog_path)
    if not path.exists():
        return {"schema": CATALOG_SCHEMA, "version": 1, "scope": "current_user_local", "applications": []}
    if path.is_symlink() or not path.is_file():
        raise PackageError("Jora catalog path must be a regular file")
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise PackageError(f"Cannot read local Jora catalog: {error}") from error
    if not isinstance(payload, dict) or payload.get("schema") != CATALOG_SCHEMA or not isinstance(payload.get("applications"), list):
        raise PackageError("Local Jora catalog has an unsupported schema")
    return payload


def publish_package(package_path: str | Path, *, channel: str = "experimental",
                    catalog_path: str | Path | None = None) -> dict[str, Any]:
    if channel not in {"experimental", "verified_preview"}:
        raise PackageError("Supported local channels: experimental, verified_preview. Stable/public release is not enabled.")
    verification = verify_package(package_path)
    if verification["verification"]["status"] == "verification_failed":
        raise PackageError("The package has failing generated-source checks and cannot be published.")
    if channel == "verified_preview" and verification["verification"]["status"] != "verified_preview":
        raise PackageError("verified_preview requires a successful static check by the Reaper CLI.")
    package = Path(package_path).expanduser().resolve(strict=True)
    manifest = _load_manifest(package)
    path = _catalog_path(catalog_path)
    if path.is_symlink():
        raise PackageError("Catalog path must not be a symbolic link")
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.parent.is_symlink():
        raise PackageError("Catalog directory must not be a symbolic link")
    catalog = list_catalog(catalog_path=path)
    app_id = manifest["app"]["app_id"]
    record = {
        "app_id": app_id,
        "display_name": manifest["app"]["display_name"],
        "slug": manifest["app"]["slug"],
        "package_path": str(package),
        "formula_hash": manifest["formula_hash"],
        "channel": channel,
        "verification": verification["verification"]["status"],
        "published_at": datetime.now(timezone.utc).isoformat(),
    }
    catalog["applications"] = [item for item in catalog["applications"] if item.get("app_id") != app_id]
    catalog["applications"].append(record)
    catalog["applications"].sort(key=lambda item: (item["display_name"].casefold(), item["app_id"]))
    encoded = _json_bytes(catalog)
    temporary = path.with_name(path.name + ".tmp")
    if temporary.exists() or temporary.is_symlink():
        temporary.unlink()
    temporary.write_bytes(encoded)
    os.replace(temporary, path)
    return {
        "schema": "duckos.jora.publish.v1",
        "published": True,
        "scope": "current_user_local",
        "channel": channel,
        "catalog_path": str(path),
        "application": record,
        "public_store": False,
        "os_installation": False,
    }
